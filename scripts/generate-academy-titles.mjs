#!/usr/bin/env node
// Scans public/academyPage/titles/*.svg and writes
// src/hooks/academyTitles.generated.ts: a full typed TITLES map containing
// every base name with its desktop + mobile dimensions for en and uk.
//
// Each title must have all four variants:
//   <base>_en.svg, <base>_uk.svg, <base>_mobile_en.svg, <base>_mobile_uk.svg
//
// Width and height come from the SVG root tag's width="…" / height="…"
// attributes (falls back to viewBox if missing).
//
// Run via: npm run generate:academy-titles
// Wired into npm scripts as `predev` and `prebuild` so it runs automatically.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const TITLES_DIR = join(ROOT, 'public', 'academyPage', 'titles')
const OUTPUT_FILE = join(ROOT, 'src', 'hooks', 'academyTitles.generated.ts')

const WIDTH_RE = /\bwidth="(\d+(?:\.\d+)?)"/
const HEIGHT_RE = /\bheight="(\d+(?:\.\d+)?)"/
const VIEWBOX_RE = /\bviewBox="(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)"/

const SUFFIXES = [
  { suffix: '_mobile_en.svg', variant: 'mobile', lang: 'en' },
  { suffix: '_mobile_uk.svg', variant: 'mobile', lang: 'uk' },
  { suffix: '_en.svg', variant: 'desktop', lang: 'en' },
  { suffix: '_uk.svg', variant: 'desktop', lang: 'uk' },
]

function extractDimensions(svg, file) {
  const head = svg.slice(0, svg.indexOf('>') + 1)
  const w = head.match(WIDTH_RE)
  const h = head.match(HEIGHT_RE)
  if (w && h) return { width: Math.round(Number(w[1])), height: Math.round(Number(h[1])) }

  const vb = head.match(VIEWBOX_RE)
  if (vb) return { width: Math.round(Number(vb[3])), height: Math.round(Number(vb[4])) }

  throw new Error(`Cannot extract dimensions from ${file}`)
}

function classify(file) {
  for (const s of SUFFIXES) {
    if (file.endsWith(s.suffix)) {
      return { base: file.slice(0, -s.suffix.length), variant: s.variant, lang: s.lang }
    }
  }
  return null
}

const files = readdirSync(TITLES_DIR)
  .filter((f) => f.endsWith('.svg'))
  .sort()

const titles = new Map()
for (const file of files) {
  const cls = classify(file)
  if (!cls) {
    console.error(`Skipping unrecognized filename: ${file}`)
    continue
  }
  const { base, variant, lang } = cls
  const svg = readFileSync(join(TITLES_DIR, file), 'utf8')
  const dim = extractDimensions(svg, file)

  if (!titles.has(base)) titles.set(base, { desktop: {}, mobile: {} })
  titles.get(base)[variant][lang] = dim
}

const bases = [...titles.keys()].sort()

const missing = []
for (const base of bases) {
  const entry = titles.get(base)
  for (const variant of ['desktop', 'mobile']) {
    for (const lang of ['en', 'uk']) {
      if (!entry[variant][lang]) missing.push(`${base}_${variant === 'mobile' ? 'mobile_' : ''}${lang}.svg`)
    }
  }
}
if (missing.length) {
  console.error(`Missing title variants:\n  - ${missing.join('\n  - ')}`)
  process.exit(1)
}

const unionType = bases.map((b) => `  | '${b}'`).join('\n')

const formatDim = (d) => `{ width: ${d.width}, height: ${d.height} }`

const entries = bases
  .map((base) => {
    const e = titles.get(base)
    return `  '${base}': {
    base: '${base}',
    alt: '${base}',
    desktop: { en: ${formatDim(e.desktop.en)}, uk: ${formatDim(e.desktop.uk)} },
    mobile:  { en: ${formatDim(e.mobile.en)},  uk: ${formatDim(e.mobile.uk)} },
  },`
  })
  .join('\n')

const output = `// AUTO-GENERATED by scripts/generate-academy-titles.mjs
// Do not edit manually — run \`npm run generate:academy-titles\` to refresh.
// Runs automatically via the \`predev\` and \`prebuild\` npm scripts.

export type AcademyTitleName =
${unionType}

export type AcademyTitleDimensions = { width: number; height: number }

export type AcademyTitleEntry = {
  base: AcademyTitleName
  alt: string
  desktop: { en: AcademyTitleDimensions; uk: AcademyTitleDimensions }
  mobile: { en: AcademyTitleDimensions; uk: AcademyTitleDimensions }
}

export const ACADEMY_TITLES: Record<AcademyTitleName, AcademyTitleEntry> = {
${entries}
}
`

writeFileSync(OUTPUT_FILE, output)
console.log(`Wrote ${bases.length} entries to ${OUTPUT_FILE}`)
